def extract_ml_feature_vector(
    tx: CandidateTransactionVO,
    merchant_median_paise: Optional[int] = None,
    time_since_last_tx_hours: Optional[float] = None,
) -> List[float]:
    """
    Extracts a normalized, numerical feature vector for multi-dimensional ML inference.
    Strictly avoids private PII, raw account tokens, or free text.
    """
    # 1. Log-transformed amount in rupees: log(1 + INR)
    amt_inr = max(0.0, tx.amount_paise / 100.0)
    amt_log = math.log1p(amt_inr)

    # 2. Ratio to merchant median (default 1.0 if unseen)
    if merchant_median_paise and merchant_median_paise > 0:
        merchant_ratio = min(10.0, tx.amount_paise / merchant_median_paise)
    else:
        merchant_ratio = 1.0

    # 3. Time delta from previous transaction (capped at 168 hours = 1 week)
    time_delta = min(168.0, max(0.0, time_since_last_tx_hours if time_since_last_tx_hours is not None else 24.0))

    # 4. Temporal features: Hour of day (normalized 0..1) and Weekend flag
    hour_norm = tx.created_at.hour / 24.0
    is_weekend = 1.0 if tx.transaction_date.weekday() >= 5 else 0.0

    return [amt_log, merchant_ratio, time_delta, hour_norm, is_weekend]


def detect_ml_isolation_forest(
    tx: CandidateTransactionVO,
    historical_feature_matrix: List[List[float]],
    candidate_features: List[float],
    min_training_samples: int = 30,
) -> Optional[AnomalyEvidenceVO]:
    """
    Executes unsupervised Isolation Forest anomaly scoring on multivariate spending vectors.
    Requires at least 30 historical transactions in the workspace to train.
    """
    if len(historical_feature_matrix) < min_training_samples or tx.direction != "outflow":
        return None

    try:
        X_train = np.array(historical_feature_matrix, dtype=np.float64)
        X_cand = np.array([candidate_features], dtype=np.float64)
        X_all = np.vstack([X_train, X_cand])

        clf = IsolationForest(
            n_estimators=100,
            contamination=0.03,  # Target top 3% extreme multivariate anomalies
            random_state=42,
            n_jobs=1,
        )
        clf.fit(X_all)

        pred = clf.predict(X_cand)[0]  # -1 for anomaly, 1 for normal
        decision_score = float(clf.decision_function(X_cand)[0])  # Lower is more anomalous

        if pred == -1 and decision_score < -0.05:
            # Scale decision score to risk score (60 to 85)
            risk_score = min(85, max(60, int(60 + abs(decision_score) * 100)))

            return AnomalyEvidenceVO(
                category=AnomalyCategory.AMOUNT,
                method=DetectionMethod.ML_ISOLATION_FOREST,
                severity=AnomalySeverity.MEDIUM if risk_score < 75 else AnomalySeverity.HIGH,
                risk_score=risk_score,
                rule_code="ML_ISOLATION_FOREST_MULTIVARIATE",
                explanation=(
                    f"Multivariate spending pattern is unusual compared to your typical transaction "
                    f"behavior across amount, timing, and merchant distribution."
                ),
                metadata={
                    "anomaly_score": round(decision_score, 4),
                    "training_samples_count": len(historical_feature_matrix),
                    "model": "IsolationForest",
                    "model_version": "v1.0.0",
                },
            )
    except Exception:
        # Graceful fallback: never crash on ML inference failures
        return None

    return None


