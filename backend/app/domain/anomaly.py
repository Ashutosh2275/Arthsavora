# 2. Statistical Anomaly Detection Engine (MAD, IQR, Rolling Z-Score)
# -----------------------------------------------------------------------------

def calculate_median_and_mad(values: List[int]) -> Tuple[float, float]:
    """
    Computes sample Median and Median Absolute Deviation (MAD).
    MAD is a robust dispersion statistic resilient to heavy financial tails.
    """
    if not values:
        return 0.0, 0.0

    sorted_vals = sorted(values)
    n = len(sorted_vals)
    mid = n // 2
    if n % 2 == 1:
        med = float(sorted_vals[mid])
    else:
        med = float(sorted_vals[mid - 1] + sorted_vals[mid]) / 2.0

    deviations = [abs(x - med) for x in sorted_vals]
    deviations.sort()
    if n % 2 == 1:
        mad = float(deviations[mid])
    else:
        mad = float(deviations[mid - 1] + deviations[mid]) / 2.0

    return med, mad


def calculate_iqr(values: List[int]) -> Tuple[float, float, float]:
    """
    Computes Quartile 1 (Q1), Quartile 3 (Q3), and Interquartile Range (IQR = Q3 - Q1).
    """
    if len(values) < 4:
        return 0.0, 0.0, 0.0

    sorted_vals = sorted(values)
    q1 = float(np.percentile(sorted_vals, 25))
    q3 = float(np.percentile(sorted_vals, 75))
    iqr = q3 - q1
    return q1, q3, iqr


def detect_merchant_amount_anomaly(
    tx: CandidateTransactionVO,
    merchant_historical_amounts: List[int],
    min_observations: int = 5,
) -> Optional[AnomalyEvidenceVO]:
    """
    Evaluates whether a transaction amount is an outlier relative to historical payments at this merchant.
    Requires minimum 5 historical observations to prevent false alarms on sparse histories.
    """
    if len(merchant_historical_amounts) < min_observations or tx.direction != "outflow":
        return None

    med, mad = calculate_median_and_mad(merchant_historical_amounts)
    # Ensure standard dispersion floor to avoid divide-by-zero on identical payments
    effective_mad = max(mad, med * 0.15, 10000.0)  # At least ₹100 floor

    # Modified Z-Score: 0.6745 * (x - med) / MAD
    modified_z = 0.6745 * (tx.amount_paise - med) / effective_mad

    # Flag if modified z-score > 3.5 (standard robust threshold)
    if modified_z >= 3.5:
        ratio = tx.amount_paise / max(1.0, med)
        score = min(85, 50 + int(modified_z * 7))
        severity = AnomalySeverity.HIGH if modified_z >= 5.0 else AnomalySeverity.MEDIUM

        return AnomalyEvidenceVO(
            category=AnomalyCategory.MERCHANT,
            method=DetectionMethod.STATISTICAL_MAD,
            severity=severity,
            risk_score=score,
            rule_code="STAT_MERCHANT_AMOUNT_MAD",
            explanation=(
                f"Amount of ₹{tx.amount_paise / 100:,.2f} is {ratio:.1f}x higher than your historical median "
                f"of ₹{med / 100:,.2f} at '{tx.merchant_name or 'this merchant'}' (Modified Z-Score: {modified_z:.1f})."
            ),
            metadata={
                "median_paise": int(round(med)),
                "mad_paise": int(round(mad)),
                "modified_z_score": round(modified_z, 2),
                "ratio_to_median": round(ratio, 2),
                "historical_sample_size": len(merchant_historical_amounts),
            },
        )
    return None


def detect_category_spike_anomaly(
    tx: CandidateTransactionVO,
    category_daily_history: List[int],
    current_month_category_total: int,
    min_days: int = 14,
) -> Optional[AnomalyEvidenceVO]:
    """
    Identifies sudden spending acceleration in a category where the current month's volume
    exceeds 2.5x the historical monthly baseline.
    """
    if len(category_daily_history) < min_days or tx.direction != "outflow":
        return None

    hist_sum = sum(category_daily_history)
    hist_days = len(category_daily_history)
    monthly_baseline = int(round((hist_sum / hist_days) * 30.4375))

    if monthly_baseline <= 0:
        return None

    ratio = current_month_category_total / monthly_baseline

    if ratio >= 2.5 and current_month_category_total >= 500000:  # >= 2.5x and at least ₹5,000 total
        return AnomalyEvidenceVO(
            category=AnomalyCategory.CATEGORY,
            method=DetectionMethod.STATISTICAL_IQR,
            severity=AnomalySeverity.MEDIUM if ratio < 3.5 else AnomalySeverity.HIGH,
            risk_score=min(80, 50 + int(ratio * 8)),
            rule_code="STAT_CATEGORY_SPIKE",
            explanation=(
                f"Total spending in '{tx.category_name or 'this category'}' this month is ₹{current_month_category_total / 100:,.2f}, "
                f"which is {ratio:.1f}x higher than your normal monthly baseline of ₹{monthly_baseline / 100:,.2f}."
            ),
            metadata={
                "current_month_total_paise": current_month_category_total,
                "historical_monthly_baseline_paise": monthly_baseline,
                "ratio": round(ratio, 2),
            },
        )
    return None


