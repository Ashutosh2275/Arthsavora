@dataclass(frozen=True)
class CandidateTransactionVO:
    """Immutable representation of a transaction evaluated for anomalies."""
    id: uuid.UUID
    workspace_id: uuid.UUID
    amount_paise: int
    currency: str
    direction: str  # inflow, outflow
    transaction_date: date
    created_at: datetime
    description: str
    account_id: Optional[uuid.UUID] = None
    category_id: Optional[uuid.UUID] = None
    merchant_id: Optional[uuid.UUID] = None
    merchant_name: Optional[str] = None
    category_name: Optional[str] = None
    transaction_type: str = "expense"
    status: str = "posted"
    transfer_id: Optional[uuid.UUID] = None


@dataclass(frozen=True)
class AnomalyEvidenceVO:
    """Individual anomaly signal generated by a rule, statistical detector, or ML model."""
    category: AnomalyCategory
    method: DetectionMethod
    severity: AnomalySeverity
    risk_score: int  # 0 to 100
    rule_code: Optional[str]
    explanation: str
    metadata: Dict[str, Any] = field(default_factory=dict)


@dataclass(frozen=True)
class DetectionResultVO:
    """Consolidated outcome of the hybrid anomaly detection pipeline."""
    is_anomalous: bool
    detection_type: str
    detection_method: str
    severity: AnomalySeverity
    risk_score: int
    explanation: str
    evidence_metadata: Dict[str, Any]
    rule_code: Optional[str] = None


