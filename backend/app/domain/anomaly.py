def evaluate_deterministic_rules(
    tx: CandidateTransactionVO,
    rules: List[Dict[str, Any]],
    recent_transactions: Optional[List[CandidateTransactionVO]] = None,
    recurring_info: Optional[Dict[str, Any]] = None,
) -> List[AnomalyEvidenceVO]:
    """
    Evaluates configured deterministic rules against candidate transaction.
    Pure functional execution with zero database side-effects.
    """
    evidences: List[AnomalyEvidenceVO] = []
    rule_map = {r.get("rule_code"): r for r in rules if r.get("is_enabled", True)}

    # 1. High Amount Rule
    high_rule = rule_map.get("RULE_HIGH_AMOUNT")
    if high_rule and tx.direction == "outflow":
        thresh = high_rule.get("threshold_config", {}).get("threshold_paise", 5000000)
        if tx.amount_paise >= thresh:
            amt_inr = tx.amount_paise / 100.0
            thresh_inr = thresh / 100.0
            score = min(90, 65 + int((tx.amount_paise - thresh) / max(1, thresh) * 20))
            evidences.append(
                AnomalyEvidenceVO(
                    category=AnomalyCategory.AMOUNT,
                    method=DetectionMethod.DETERMINISTIC_RULE,
                    severity=AnomalySeverity.HIGH if tx.amount_paise < thresh * 2 else AnomalySeverity.CRITICAL,
                    risk_score=score,
                    rule_code="RULE_HIGH_AMOUNT",
                    explanation=f"Transaction amount of ₹{amt_inr:,.2f} exceeds your high-value threshold of ₹{thresh_inr:,.2f}.",
                    metadata={
                        "amount_paise": tx.amount_paise,
                        "threshold_paise": thresh,
                        "ratio": round(tx.amount_paise / thresh, 2),
                    },
                )
            )

    # 2. Frequency Burst Rule (Multiple transactions to same merchant in short window)
    burst_rule = rule_map.get("RULE_FREQUENCY_BURST")
    if burst_rule and recent_transactions and tx.merchant_name:
        cfg = burst_rule.get("threshold_config", {})
        win_mins = cfg.get("window_minutes", 30)
        count_thresh = cfg.get("count_threshold", 3)

        # Match transactions with same merchant created within window
        cutoff = tx.created_at - timedelta(minutes=win_mins)
        similar = [
            t for t in recent_transactions
            if t.id != tx.id
            and t.merchant_name
            and t.merchant_name.lower().strip() == tx.merchant_name.lower().strip()
            and t.created_at >= cutoff
        ]

        if len(similar) + 1 >= count_thresh:
            total_count = len(similar) + 1
            evidences.append(
                AnomalyEvidenceVO(
                    category=AnomalyCategory.FREQUENCY,
                    method=DetectionMethod.DETERMINISTIC_RULE,
                    severity=AnomalySeverity.HIGH,
                    risk_score=75,
                    rule_code="RULE_FREQUENCY_BURST",
                    explanation=f"{total_count} transactions recorded at '{tx.merchant_name}' within a {win_mins}-minute window.",
                    metadata={
                        "merchant_name": tx.merchant_name,
                        "transaction_count": total_count,
                        "window_minutes": win_mins,
                        "related_transaction_ids": [str(t.id) for t in similar],
                    },
                )
            )

    # 3. Recurring Hike Rule (Subscription price unexpected jump)
    hike_rule = rule_map.get("RULE_RECURRING_HIKE")
    if hike_rule and recurring_info and recurring_info.get("is_recurring"):
        exp_paise = recurring_info.get("expected_amount_paise", 0)
        cfg = hike_rule.get("threshold_config", {})
        var_thresh = cfg.get("variance_pct_threshold", 0.15)
        min_inc_paise = cfg.get("min_increase_paise", 50000)

        if exp_paise > 0 and tx.amount_paise > exp_paise:
            increase_paise = tx.amount_paise - exp_paise
            pct_increase = increase_paise / exp_paise

            if pct_increase >= var_thresh and increase_paise >= min_inc_paise:
                evidences.append(
                    AnomalyEvidenceVO(
                        category=AnomalyCategory.RECURRING,
                        method=DetectionMethod.DETERMINISTIC_RULE,
                        severity=AnomalySeverity.MEDIUM,
                        risk_score=60,
                        rule_code="RULE_RECURRING_HIKE",
                        explanation=(
                            f"Recurring payment of ₹{tx.amount_paise / 100:,.2f} is {pct_increase * 100:.1f}% "
                            f"(₹{increase_paise / 100:,.2f}) higher than expected scheduled amount of ₹{exp_paise / 100:,.2f}."
                        ),
                        metadata={
                            "expected_amount_paise": exp_paise,
                            "actual_amount_paise": tx.amount_paise,
                            "increase_paise": increase_paise,
                            "percentage_increase": round(pct_increase * 100, 2),
                            "recurring_definition_id": str(recurring_info.get("definition_id", "")),
                        },
                    )
                )

    # 4. Cancelled Recurring Charge Rule
    cancel_rule = rule_map.get("RULE_CANCELLED_RECURRING")
    if cancel_rule and recurring_info and recurring_info.get("status") in ("cancelled", "inactive"):
        evidences.append(
            AnomalyEvidenceVO(
                category=AnomalyCategory.RECURRING,
                method=DetectionMethod.DETERMINISTIC_RULE,
                severity=AnomalySeverity.CRITICAL,
                risk_score=90,
                rule_code="RULE_CANCELLED_RECURRING",
                explanation=(
                    f"Transaction of ₹{tx.amount_paise / 100:,.2f} detected for '{recurring_info.get('name', 'Subscription')}' "
                    f"which was previously marked as cancelled."
                ),
                metadata={
                    "recurring_name": recurring_info.get("name"),
                    "recurring_definition_id": str(recurring_info.get("definition_id", "")),
                    "recurring_status": recurring_info.get("status"),
                },
            )
        )

    # 5. Duplicate Candidate Rule
    dup_rule = rule_map.get("RULE_DUPLICATE_CANDIDATE")
    if dup_rule and recent_transactions:
        cfg = dup_rule.get("threshold_config", {})
        win_hrs = cfg.get("window_hours", 48)
        cutoff = tx.created_at - timedelta(hours=win_hrs)

        dups = [
            t for t in recent_transactions
            if t.id != tx.id
            and t.amount_paise == tx.amount_paise
            and t.currency == tx.currency
            and t.direction == tx.direction
            and t.created_at >= cutoff
            and (
                (t.merchant_name and tx.merchant_name and t.merchant_name.lower().strip() == tx.merchant_name.lower().strip())
                or (t.account_id and tx.account_id and t.account_id == tx.account_id)
            )
        ]

        if dups:
            target_dup = dups[0]
            evidences.append(
                AnomalyEvidenceVO(
                    category=AnomalyCategory.DUPLICATE,
                    method=DetectionMethod.DETERMINISTIC_RULE,
                    severity=AnomalySeverity.MEDIUM,
                    risk_score=65,
                    rule_code="RULE_DUPLICATE_CANDIDATE",
                    explanation=(
                        f"Potential duplicate payment of ₹{tx.amount_paise / 100:,.2f} matching an earlier "
                        f"transaction on {target_dup.transaction_date.isoformat()}."
                    ),
                    metadata={
                        "duplicate_transaction_id": str(target_dup.id),
                        "duplicate_date": target_dup.transaction_date.isoformat(),
                        "amount_paise": tx.amount_paise,
                    },
                )
            )

    return evidences


