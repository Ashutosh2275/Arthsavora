# 4. Exception Matching Engine (Whitelist Enforcement)
# -----------------------------------------------------------------------------

def matches_detection_exception(
    tx: CandidateTransactionVO,
    exceptions: List[Dict[str, Any]],
    as_of_date: Optional[date] = None,
) -> Optional[Dict[str, Any]]:
    """
    Verifies if candidate transaction matches an active, unexpired detection exception (whitelist).
    """
    as_of = as_of_date or date.today()

    for exc in exceptions:
        # Expiry check
        exp = exc.get("expires_at")
        if exp:
            exp_date = exp if isinstance(exp, date) else datetime.strptime(str(exp), "%Y-%m-%d").date()
            if as_of > exp_date:
                continue

        # Merchant match
        if exc.get("merchant_id") and tx.merchant_id:
            if str(exc["merchant_id"]) != str(tx.merchant_id):
                continue

        # Merchant name pattern match
        pattern = exc.get("merchant_name_pattern")
        if pattern and tx.merchant_name:
            if not re.search(pattern, tx.merchant_name, re.IGNORECASE):
                continue

        # Category match
        if exc.get("category_id") and tx.category_id:
            if str(exc["category_id"]) != str(tx.category_id):
                continue

        # Account match
        if exc.get("account_id") and tx.account_id:
            if str(exc["account_id"]) != str(tx.account_id):
                continue

        # Ceiling amount check
        max_paise = exc.get("max_amount_paise")
        if max_paise is not None and tx.amount_paise > max_paise:
            continue

        # If all specified criteria matched, this exception applies
        return exc

    return None


